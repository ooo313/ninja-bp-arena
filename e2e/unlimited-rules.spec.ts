import { expect, test } from '@playwright/test'

test('命名保存无限局规则，刷新后可选用和删除，超时自动确认预览', async ({ page }) => {
  await page.goto('/settings')
  await page.getByRole('combobox', { name: '赛制', exact: true }).selectOption('0')
  await expect(page.getByLabel('跨局已使用资源锁定', { exact: true })).toBeChecked()
  await expect(page.getByLabel('每局结束后交换左右位置与先后手')).toBeChecked()
  await page.getByLabel('秒数', { exact: true }).fill('5')
  await page.getByLabel('新规则名称').fill('好友换边赛')
  await page.getByRole('button', { name: '另存为新规则' }).click()
  await page.reload()
  await expect(page.getByRole('region', { name: '已保存的规则' })).toContainText('好友换边赛 · 无上限')

  await page.goto('/')
  await page.getByRole('banner').getByRole('button', { name: '开始 BP', exact: true }).click()
  await page.getByLabel('规则模板').selectOption({ label: '好友换边赛' })
  await expect(page.getByRole('dialog')).toContainText('无上限')
  await page.clock.install()
  await page.getByRole('button', { name: '开始比赛', exact: true }).click()
  const grid = page.getByRole('grid', { name: '忍者资源列表' })
  await expect(grid.locator('.arena-rank').first()).toBeVisible()
  const ranks = await grid.locator('.arena-rank').allTextContents()
  expect(ranks.length).toBeGreaterThan(0)
  expect(ranks).toEqual([...ranks].sort((a, b) => 'SABC'.indexOf(a) - 'SABC'.indexOf(b)))
  const choice = grid.getByRole('gridcell', { name: '预览忍者 漩涡鸣人', exact: true })
  await page.getByRole('textbox', { name: '搜索忍者' }).fill('漩涡鸣人')
  await choice.click()
  await expect(choice).toHaveAttribute('aria-pressed', 'true')
  await page.clock.fastForward(6_000)
  await expect(choice).toHaveAttribute('data-state', 'BANNED')
  await expect(page.getByRole('button', { name: '重新计时' })).toHaveCount(0)

  await page.goto('/settings')
  await page.getByRole('button', { name: '删除规则 好友换边赛' }).click()
  await page.reload()
  await expect(page.getByRole('region', { name: '已保存的规则' })).toHaveCount(0)
})
